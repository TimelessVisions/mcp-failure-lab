"""Release checksums over the export the manifest describes.

Two defects motivated this module, and both are worth stating because the code
is shaped around not repeating them.

The first was hashing the *directory*. ``SHA256SUMS`` was generated by walking
the export tree recursively, but by the time the gate reaches the hashing step
it has already run ``uv sync`` and ``npm ci`` inside that tree. The checksums
therefore covered a virtualenv, a ``node_modules``, a built bundle and several
caches — tens of thousands of files that are not part of any release, whose
contents differ per machine, and whose presence made the file useless as a
release integrity record.

The second was fixing that by reading the manifest, but skipping quietly:

    if not file.is_file():
        continue

A manifest-listed file that had gone missing simply did not appear in
``SHA256SUMS``, and nothing failed. That is the exact failure a checksum file
exists to catch — the release is short a file — expressed as silence. A
disagreement between the manifest and the tree is the most interesting thing
this code can find, so every disagreement is an error and none is a ``continue``.

The rule chosen here for the manifest itself, of the two the export contract
permits: ``EXPORT-MANIFEST.json`` is appended separately and must **not** appear
in its own included list. That makes the line count exactly

    unique included files + 1

which is an assertion with no free parameters, rather than a count that has to
be explained. ``SHA256SUMS`` never hashes itself.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from pydantic import BaseModel, ConfigDict, Field, ValidationError

#: The export's own two release files. Neither may be listed as included: the
#: manifest is appended by this module exactly once, and a checksum file that
#: hashes itself cannot be written.
MANIFEST_FILENAME = "EXPORT-MANIFEST.json"
CHECKSUMS_FILENAME = "SHA256SUMS"

#: Directories the export gate creates inside the destination by installing and
#: building in place. They are on disk on purpose — the later gate steps need
#: them — and none of them may reach the release checksums. Nothing here filters
#: them out at hash time; they are excluded structurally, because this module
#: never walks the tree. The tuple exists so a test can name what must stay out.
GENERATED_DIRECTORIES: tuple[str, ...] = (
    ".venv",
    "node_modules",
    "dist",
    ".pytest_cache",
    "__pycache__",
    ".ruff_cache",
    ".mypy_cache",
)

#: ``C:\path`` / ``C:/path``. Absolute on Windows, and merely a relative path
#: with an odd first segment on POSIX, which is how such a path slips through a
#: check that only asks ``PurePosixPath.is_absolute()``.
_WINDOWS_ABSOLUTE = re.compile(r"^[A-Za-z]:[\\/]")

#: ``\\server\share`` and ``//server/share``. A UNC path names another host.
_UNC = re.compile(r"^([\\]{2}|/{2})[^\\/]")

#: One ``SHA256SUMS`` line: 64 lowercase hex digits, two spaces, then the path.
#: Two spaces is the coreutils binary-mode separator, so ``sha256sum -c`` reads
#: what this writes.
_LINE = re.compile(r"^([0-9a-f]{64})  (.+)$")


class ChecksumError(Exception):
    """A disagreement between the manifest, the tree, and the checksum file.

    Every rule in this module raises rather than skipping. The message names the
    path, because "some file was missing" is not actionable at release time.
    """


class ManifestEntry(BaseModel):
    """One included path from ``EXPORT-MANIFEST.json``."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    path: str
    reason: str


class ExportManifest(BaseModel):
    """The manifest as this module requires it to be.

    Unknown fields are rejected. The manifest is written by this repository's own
    export command, so an unexpected key means either a version skew or a file
    that is not the manifest at all, and hashing a release against a document
    that is not the release description is worse than stopping.
    """

    model_config = ConfigDict(extra="forbid")

    manifest_version: str
    generated_at: str
    harness_version: str
    summary: dict[str, object]
    included: list[ManifestEntry]
    withheld_by_reason: dict[str, int] = Field(default_factory=dict)
    note: str = ""


@dataclass(frozen=True)
class ChecksumLine:
    """One verified line: the digest, and the path it was computed over."""

    digest: str
    path: str

    def render(self) -> str:
        return f"{self.digest}  {self.path}"


@dataclass(frozen=True)
class ChecksumReport:
    """The machine-readable result of generating or checking.

    Emitted as JSON by the CLI so the gate and its workflow can assert on the
    numbers rather than parsing prose.
    """

    mode: str
    root: str
    manifest: str
    checksums: str
    manifest_included: int
    hashed_files: int
    lines: int
    expected_lines: int
    manifest_sha256: str
    checksums_sha256: str
    verified: bool

    def to_dict(self) -> dict[str, object]:
        return {
            "mode": self.mode,
            "root": self.root,
            "manifest": self.manifest,
            "checksums": self.checksums,
            "manifest_included": self.manifest_included,
            "hashed_files": self.hashed_files,
            "lines": self.lines,
            "expected_lines": self.expected_lines,
            "manifest_sha256": self.manifest_sha256,
            "checksums_sha256": self.checksums_sha256,
            "verified": self.verified,
        }


def sha256_file(path: Path) -> str:
    """Digest a file's bytes, read in chunks so a large asset is not resident."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def load_manifest(path: Path) -> ExportManifest:
    """Read and validate ``EXPORT-MANIFEST.json``."""
    if not path.is_file():
        raise ChecksumError(f"no export manifest at {path}")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ChecksumError(f"{path}: not readable as JSON ({exc})") from exc
    if not isinstance(payload, dict):
        raise ChecksumError(f"{path}: manifest is not a JSON object")
    try:
        return ExportManifest.model_validate(payload)
    except ValidationError as exc:
        raise ChecksumError(f"{path}: not a valid export manifest\n{exc}") from exc


def _reject_unsafe_spelling(raw: str) -> None:
    """Refuse a path whose *spelling* is unsafe, before touching the filesystem.

    These are checked on the literal string rather than on a resolved path
    because several of them stop being visible once resolution has happened: on
    POSIX, ``C:\\evil`` resolves to a perfectly ordinary relative directory, and
    a traversal that is cancelled out by a later segment resolves inside the root
    while still describing a walk outside it.
    """
    if not raw or not raw.strip():
        raise ChecksumError("the manifest lists an empty path")
    if raw != raw.strip():
        raise ChecksumError(f"{raw!r}: path has leading or trailing whitespace")
    if "\x00" in raw:
        raise ChecksumError(f"{raw!r}: path contains a NUL byte")
    if _UNC.match(raw):
        raise ChecksumError(f"{raw!r}: UNC paths name another host and are never exported")
    if raw.startswith("/"):
        raise ChecksumError(f"{raw!r}: absolute POSIX path; manifest paths are export-relative")
    if _WINDOWS_ABSOLUTE.match(raw):
        raise ChecksumError(f"{raw!r}: absolute Windows path; manifest paths are export-relative")
    if "\\" in raw:
        raise ChecksumError(f"{raw!r}: backslash separator; manifest paths are POSIX")
    segments = raw.split("/")
    if ".." in segments:
        raise ChecksumError(f"{raw!r}: '..' traversal is never exported")
    if raw in {MANIFEST_FILENAME, CHECKSUMS_FILENAME}:
        raise ChecksumError(
            f"{raw}: the export's own release files must not be listed as included; "
            f"{MANIFEST_FILENAME} is appended exactly once and {CHECKSUMS_FILENAME} "
            "never hashes itself"
        )


def _normalise(raw: str) -> str:
    """Collapse a path to one canonical spelling, without resolving symlinks.

    ``a/b``, ``./a/b`` and ``a//b`` are the same file under three names. Two
    entries that land on the same normalised form are a duplicate even though a
    string comparison of the manifest would not have said so.
    """
    parts = [segment for segment in raw.split("/") if segment not in ("", ".")]
    return PurePosixPath(*parts).as_posix() if parts else ""


def _resolve_within(root: Path, relative: str) -> Path:
    """Locate one manifest path inside the export, refusing anything that escapes.

    A symlink is refused outright rather than followed. The export contract does
    not model symlinks: every included file is copied with ``shutil.copy2``, so a
    symlink in a materialised export is either a link the copy did not create or
    a link into the machine the export was built on. Neither belongs in a release
    whose whole claim is that its bytes are what a reader gets.
    """
    root_real = root.resolve(strict=True)
    candidate = root_real / relative

    walked = root_real
    for segment in relative.split("/"):
        walked = walked / segment
        if walked.is_symlink():
            raise ChecksumError(
                f"{relative}: '{segment}' is a symbolic link; the export contract does "
                "not model symlinks, so a release checksum will not follow one"
            )

    resolved = candidate.resolve()
    if resolved != root_real and root_real not in resolved.parents:
        raise ChecksumError(f"{relative}: resolves outside the export root ({resolved})")
    return candidate


def _validated_paths(manifest: ExportManifest, root: Path) -> list[str]:
    """Every included path, checked against all path and existence rules.

    Returns the deterministic sorted order the checksum file is written in.
    """
    seen_spelling: dict[str, str] = {}
    seen_identity: dict[Path, str] = {}
    paths: list[str] = []

    for entry in manifest.included:
        raw = entry.path
        _reject_unsafe_spelling(raw)
        normalised = _normalise(raw)
        if not normalised:
            raise ChecksumError(f"{raw!r}: path names no file")
        if normalised in seen_spelling:
            previous = seen_spelling[normalised]
            if previous == raw:
                raise ChecksumError(f"{raw}: listed twice in the manifest")
            raise ChecksumError(
                f"{raw}: names the same file as {previous!r} under a second spelling"
            )
        seen_spelling[normalised] = raw

        located = _resolve_within(root, normalised)
        if not located.exists():
            raise ChecksumError(f"{normalised}: listed in the manifest but missing from the export")
        if located.is_dir():
            raise ChecksumError(
                f"{normalised}: is a directory, but the manifest lists it as a file"
            )
        if not located.is_file():
            raise ChecksumError(f"{normalised}: is not a regular file")

        identity = located.resolve()
        if identity in seen_identity:
            raise ChecksumError(
                f"{normalised}: is the same file on disk as {seen_identity[identity]!r}"
            )
        seen_identity[identity] = normalised
        paths.append(normalised)

    return sorted(paths)


def compute(root: Path, manifest_path: Path) -> tuple[list[ChecksumLine], ExportManifest]:
    """Hash exactly what the manifest describes, plus the manifest itself.

    Nothing walks the tree. ``.venv``, ``node_modules``, ``dist`` and every cache
    the gate created during its earlier steps stay on disk untouched and are
    structurally incapable of reaching this list, because the only source of
    paths is the manifest.
    """
    manifest = load_manifest(manifest_path)
    paths = _validated_paths(manifest, root)

    root_real = root.resolve(strict=True)
    lines = [ChecksumLine(sha256_file(root_real / path), path) for path in paths]

    manifest_relative = _relative_to_root(manifest_path, root_real)
    lines.append(ChecksumLine(sha256_file(manifest_path), manifest_relative))
    return lines, manifest


def _relative_to_root(path: Path, root_real: Path) -> str:
    """Name the manifest the way every other line names its file."""
    resolved = path.resolve()
    if resolved == root_real or root_real not in resolved.parents:
        raise ChecksumError(f"{path}: the manifest must live inside the export root")
    return resolved.relative_to(root_real).as_posix()


def parse(text: str) -> list[ChecksumLine]:
    """Read a ``SHA256SUMS`` back, refusing anything malformed.

    Written and re-read rather than trusted from memory: the point of the second
    pass is to verify the file that will actually ship, not the list that was
    intended.
    """
    if not text.endswith("\n"):
        raise ChecksumError(f"{CHECKSUMS_FILENAME}: does not end with a newline")
    if text.endswith("\n\n"):
        raise ChecksumError(f"{CHECKSUMS_FILENAME}: ends with more than one newline")

    lines: list[ChecksumLine] = []
    for number, raw in enumerate(text.split("\n")[:-1], start=1):
        match = _LINE.match(raw)
        if match is None:
            raise ChecksumError(f"{CHECKSUMS_FILENAME}:{number}: malformed line {raw!r}")
        lines.append(ChecksumLine(match.group(1), match.group(2)))
    return lines


def verify(root: Path, manifest_path: Path, checksums_path: Path) -> ChecksumReport:
    """Re-read a written ``SHA256SUMS`` and prove it, line by line.

    Three separate disagreements are checked, because they fail differently: a
    digest that no longer matches means the file changed; a manifest entry with
    no line means the generator dropped something; a line with no manifest entry
    means something was hashed that the release does not claim to contain.
    """
    if not checksums_path.is_file():
        raise ChecksumError(f"no checksum file at {checksums_path}")

    manifest = load_manifest(manifest_path)
    root_real = root.resolve(strict=True)
    expected_paths = _validated_paths(manifest, root)
    manifest_relative = _relative_to_root(manifest_path, root_real)
    approved = [*expected_paths, manifest_relative]

    lines = parse(checksums_path.read_text(encoding="utf-8"))

    listed: dict[str, str] = {}
    for line in lines:
        if line.path in listed:
            raise ChecksumError(f"{line.path}: listed twice in {CHECKSUMS_FILENAME}")
        listed[line.path] = line.digest

    approved_set = set(approved)
    for path in sorted(set(listed) - approved_set):
        raise ChecksumError(
            f"{path}: present in {CHECKSUMS_FILENAME} but not in the approved export set"
        )
    for path in sorted(approved_set - set(listed)):
        raise ChecksumError(f"{path}: in the manifest but absent from {CHECKSUMS_FILENAME}")

    if [line.path for line in lines] != [*sorted(expected_paths), manifest_relative]:
        raise ChecksumError(f"{CHECKSUMS_FILENAME}: paths are not in the deterministic order")

    for line in lines:
        actual = sha256_file(root_real / line.path)
        if actual != line.digest:
            raise ChecksumError(
                f"{line.path}: checksum differs — recorded {line.digest}, computed {actual}"
            )

    expected_lines = len(expected_paths) + 1
    if len(lines) != expected_lines:
        raise ChecksumError(
            f"{CHECKSUMS_FILENAME}: {len(lines)} line(s), expected {expected_lines} "
            f"({len(expected_paths)} included file(s) + the manifest)"
        )

    return ChecksumReport(
        mode="check",
        root=str(root_real),
        manifest=manifest_relative,
        checksums=_relative_to_root(checksums_path, root_real),
        manifest_included=len(manifest.included),
        hashed_files=len(expected_paths),
        lines=len(lines),
        expected_lines=expected_lines,
        manifest_sha256=sha256_file(manifest_path),
        checksums_sha256=sha256_file(checksums_path),
        verified=True,
    )


def generate(root: Path, manifest_path: Path, checksums_path: Path) -> ChecksumReport:
    """Write ``SHA256SUMS``, then prove the file that was written.

    The assertion on the line count is the cheap version of the whole contract:
    one line per unique included file, plus one for the manifest. A silently
    skipped file, a duplicate, or a stray extra entry all change that number, so
    the count is checked before anything downstream trusts the file.
    """
    lines, manifest = compute(root, manifest_path)

    expected_lines = len(manifest.included) + 1
    if len(lines) != expected_lines:
        raise ChecksumError(
            f"{CHECKSUMS_FILENAME}: computed {len(lines)} line(s), expected {expected_lines}"
        )

    checksums_path.parent.mkdir(parents=True, exist_ok=True)
    checksums_path.write_text(
        "\n".join(line.render() for line in lines) + "\n",
        encoding="utf-8",
        newline="\n",
    )

    report = verify(root, manifest_path, checksums_path)
    return ChecksumReport(
        mode="generate",
        root=report.root,
        manifest=report.manifest,
        checksums=report.checksums,
        manifest_included=report.manifest_included,
        hashed_files=report.hashed_files,
        lines=report.lines,
        expected_lines=report.expected_lines,
        manifest_sha256=report.manifest_sha256,
        checksums_sha256=report.checksums_sha256,
        verified=report.verified,
    )
